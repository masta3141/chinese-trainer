function t(key){
  var lang = (settings && settings.lang) || 'de';
  return (I18N[lang] && I18N[lang][key] !== undefined) ? I18N[lang][key] : (I18N.de[key] !== undefined ? I18N.de[key] : key);
}
function tf(key){
  var str = t(key);
  var args = Array.prototype.slice.call(arguments, 1);
  return str.replace(/\{(\d+)\}/g, function(m, i){ return args[i] !== undefined ? args[i] : m; });
}

function applyStaticTranslations(){
  Array.prototype.forEach.call(document.querySelectorAll('[data-i18n]'), function(el){
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  Array.prototype.forEach.call(document.querySelectorAll('[data-i18n-placeholder]'), function(el){
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  Array.prototype.forEach.call(document.querySelectorAll('[data-i18n-title]'), function(el){
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  document.documentElement.lang = settings.lang || 'de';
  var btnLangEl = document.getElementById('btnLang');
  if (btnLangEl) btnLangEl.textContent = LANG_FLAGS[settings.lang || 'de'];
  Array.prototype.forEach.call(document.querySelectorAll('.lang-option'), function(btn){
    btn.classList.toggle('active', btn.getAttribute('data-lang') === (settings.lang || 'de'));
  });
}

function setLanguage(lang){
  if (!I18N[lang]) return;
  settings.lang = lang;
  saveSettings(settings);
  applyStaticTranslations();
  buildPoolLegend();
  buildPoolPanel();
  if (typeof storiesState !== 'undefined') {
    // re-render whichever tab is currently active, so dynamic content re-translates too
    if (storiesState.view) { /* stories module loaded further down; safe to call once defined */ }
  }
  render();
  var statsView = document.getElementById('statsPageView');
  if (statsView && statsView.style.display !== 'none') { try { renderStatsTab(); } catch(e){} }
  var storiesView = document.getElementById('storiesView');
  if (storiesView && storiesView.style.display !== 'none') { try { renderStories(); } catch(e){} }
}
